"""module1のモジュール"""


def add(a: int, b: int) -> int:
    """
    2つの整数を足し合わせる関数

    Args:
        a (int): 整数
        b (int): 整数

    Returns:
        int: 2つの整数の和
    """
    return a + b


def subtract(a: int, b: int) -> int:
    """
    2つの整数を引き算する関数

    Args:
        a (int): 整数
        b (int): 整数

    Returns:
        int: 2つの整数の差
    """
    return a - b
